/**
 * /clear starts the canvas over: a dev Ember (own EMBER_HOME), a canvas fed a made-up
 * session through window.__ember.loomFeed (no model, no real transcript), then `/clear`
 * the way Claude Code 2.1 records it: the session moves to a new transcript (main reports a
 * switch, here window.__ember.loomSwitch) whose first lines are the command and its empty
 * output. Checks that the turns and the rail of turn points on the left go, that a /clear
 * recorded at the end of the old log works the same, and that the new session builds its
 * rail as usual. Also: a switch without /clear (`/resume`) keeps the history with a seam,
 * and other slash commands stay quiet notes.
 *
 *   npm run build; node scripts/probe-clear.mjs [out-dir]
 *
 * Nothing is typed into any terminal.
 */
import { spawn } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const REPO = new URL('..', import.meta.url).pathname.slice(1).replace(/\/$/, '')
const OUT = process.argv[2] ?? join(process.env.TEMP ?? '.', 'ember-clear-shots')
const EMBER_HOME = join(process.env.TEMP ?? '.', 'ember-probe-clear')
rmSync(EMBER_HOME, { recursive: true, force: true })
mkdirSync(EMBER_HOME, { recursive: true })
mkdirSync(OUT, { recursive: true })
writeFileSync(join(EMBER_HOME, 'config.json'), JSON.stringify({ agent: { onboarded: true }, brain: { sync: false } }))
const PORT = 9423
const child = spawn(join(REPO, 'node_modules/electron/dist/electron.exe'), ['.', `--remote-debugging-port=${PORT}`], {
  cwd: REPO,
  stdio: 'ignore',
  env: { ...process.env, EMBER_HOME, EMBER_PROBE_BOUNDS: '1280x800', EMBER_PROBE_INACTIVE: '1' },
})
const wait = (ms) => new Promise((r) => setTimeout(r, ms))

let n = 0
const t0 = Date.parse('2026-11-03T09:00:00Z')
const at = () => new Date(t0 + n * 1000).toISOString()
const u = (content, extra = {}) => ({ type: 'user', uuid: `u${++n}`, timestamp: at(), message: { role: 'user', content }, ...extra })
const a = (text) => ({ type: 'assistant', uuid: `a${++n}`, timestamp: at(), message: { role: 'assistant', content: [{ type: 'text', text }] } })
const tool = (name, input) => ({ type: 'assistant', uuid: `a${++n}`, timestamp: at(), message: { role: 'assistant', content: [{ type: 'tool_use', id: `t${n}`, name, input }] } })
// What a local command writes: a meta caveat, the command, what it printed.
const clearLines = (cmd = '/clear') => [
  u('Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.', { isMeta: true }),
  u(`<command-name>${cmd}</command-name>\n            <command-message>${cmd.slice(1)}</command-message>\n            <command-args></command-args>`),
  u('<local-command-stdout></local-command-stdout>'),
]
const session = (tag, k) => {
  const out = []
  for (let i = 1; i <= k; i++) out.push(u(`${tag} turn ${i}: tell me about part ${i}`), a(`${tag} answer ${i}. `.repeat(20)))
  return out
}

try {
  let target
  for (let i = 0; i < 60 && !target; i++) {
    await wait(500)
    try {
      target = (await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json()).find((t) => t.type === 'page')
    } catch {}
  }
  const ws = new WebSocket(target.webSocketDebuggerUrl)
  await new Promise((r) => ws.addEventListener('open', r, { once: true }))
  let id = 0
  const pending = new Map()
  ws.addEventListener('message', (e) => {
    const m = JSON.parse(e.data)
    pending.get(m.id)?.(m.result ?? m.error)
    pending.delete(m.id)
  })
  const send = (method, params = {}) =>
    new Promise((r) => {
      pending.set(++id, r)
      ws.send(JSON.stringify({ id, method, params }))
    })
  const ev = async (expression) => {
    const r = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true })
    if (r?.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails).slice(0, 400))
    return r?.result?.value
  }
  const shot = async (name) => {
    const r = await send('Page.captureScreenshot', { format: 'png' })
    writeFileSync(join(OUT, `${name}.png`), Buffer.from(r.data, 'base64'))
  }

  await wait(5000)
  const first = await ev('window.__ember.activeTab()')
  const tab = await ev('window.__ember.newLoom()')
  await ev(`window.__ember.closeTab(${JSON.stringify(first)})`)
  await ev(`window.__ember.activate(${JSON.stringify(tab)})`)
  await wait(1500)
  const sid = await ev(`window.__ember.sessions()[0].id`)
  await ev(`window.__ember.term(${JSON.stringify(sid)}).write('\\x1b]0;\\u2733 Claude Code\\x07'), true`)
  await wait(2500)
  await ev(`(() => { const st = document.createElement('style'); st.textContent = '.loom { display: block !important; height: 640px !important; }'; document.head.appendChild(st); return true })()`)

  const LOOM = `document.querySelector('.loom[data-tab-id="${tab}"]')`
  const state = () =>
    ev(`(() => { const L = ${LOOM}; const flow = L.querySelector('.loom-flow')
      const turns = [...flow.querySelectorAll(':scope > .loom-turn')].filter((t) => t.childElementCount)
      const rail = L.querySelector('.loom-rail')
      return {
        turns: turns.length,
        asks: [...flow.querySelectorAll('.loom-ask-text')].map((x) => x.textContent.slice(0, 14)),
        says: flow.querySelectorAll('.loom-say').length,
        seams: flow.querySelectorAll('.loom-seam').length,
        notes: flow.querySelectorAll('[data-cmd]').length,
        rail: rail.children.length, railOn: rail.classList.contains('is-on'),
        hint: !L.querySelector('.loom-hint').classList.contains('is-gone'),
        plan: !!L.querySelector('.loom-plan.is-on'),
      } })()`)
  const log = []
  let fails = 0
  const check = (label, s, ok) => {
    if (!ok) fails++
    log.push(`${ok ? 'PASS' : 'FAIL'} ${label.padEnd(44)} turns ${s.turns}  rail ${s.rail}${s.railOn ? ' (on)' : ''}  says ${s.says}  seams ${s.seams}  notes ${s.notes}  hint ${s.hint}  plan ${s.plan}  asks ${JSON.stringify(s.asks)}`)
  }
  const feed = (lines) => ev(`window.__ember.loomFeed(${JSON.stringify(tab)}, ${JSON.stringify(lines)})`)
  const switchTo = (first = false) => ev(`window.__ember.loomSwitch(${JSON.stringify(tab)}, ${first})`)

  // 1. A session with three turns and a plan.
  await switchTo(true)
  await feed([
    ...session('old', 3),
    tool('TodoWrite', { todos: [{ content: 'step one', status: 'in_progress', activeForm: 'stepping' }, { content: 'step two', status: 'pending' }] }),
  ])
  await wait(1200)
  let s = await state()
  check('old session builds its rail', s, s.turns === 3 && s.rail === 3 && s.railOn && s.says === 3)
  await shot('1-old')

  // 2. /clear, as Claude Code 2.1 does it: a new transcript that starts with the command.
  await switchTo(false)
  await feed(clearLines('/clear'))
  await wait(1200)
  s = await state()
  check('/clear (top of new log): canvas + rail empty', s, s.turns === 0 && s.rail === 0 && !s.railOn && s.says === 0 && s.seams === 0 && s.notes === 0 && s.hint && !s.plan)
  await shot('2-cleared')

  // 3. The new session builds its own rail from nothing.
  await feed(session('new', 2))
  await wait(1200)
  s = await state()
  check('new session builds a fresh rail', s, s.turns === 2 && s.rail === 2 && s.railOn && s.asks.every((x) => x.startsWith('new')))
  await shot('3-new')

  // 4. /clear (alias /reset) recorded at the end of the old log, then the switch: empty, no seam.
  await feed(clearLines('/reset'))
  await switchTo(false)
  await wait(1200)
  s = await state()
  check('/reset (end of old log) then switch: empty', s, s.turns === 0 && s.rail === 0 && s.seams === 0 && s.notes === 0)

  // 5. A switch with no /clear (/resume, `claude` again) keeps what was there, with a seam.
  await feed(session('third', 2))
  await switchTo(false)
  await feed(session('resumed', 1))
  await wait(1200)
  s = await state()
  check('/resume keeps history with a seam', s, s.turns === 3 && s.rail === 3 && s.seams === 1)

  // 6. Other slash commands are still quiet notes, not turns.
  await feed([u('<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>'), u('<local-command-stdout>Set model to opus</local-command-stdout>')])
  await wait(600)
  s = await state()
  check('/model stays a note, not a turn', s, s.turns === 3 && s.rail === 3 && s.notes === 2)
  await shot('4-end')

  console.log(log.join('\n'))
  console.log(fails ? `${fails} FAILED` : 'all passed')
  ws.close()
  process.exitCode = fails ? 1 : 0
} finally {
  spawn('taskkill', ['/PID', String(child.pid), '/T', '/F'], { stdio: 'ignore' })
  // Electron can relaunch itself (--gpu-relaunched) outside the tree taskkill sees; a
  // survivor would keep the port and answer the next run with the old build.
  spawn('powershell', ['-NoProfile', '-Command', `Get-CimInstance Win32_Process -Filter "name='electron.exe'" | Where-Object { $_.CommandLine -match 'remote-debugging-port=${PORT}' } | ForEach-Object { Stop-Process -Id $_.ProcessId -Force -ErrorAction SilentlyContinue }`], { stdio: 'ignore' })
}
